describe('summary page account filter (functional)', () => {
    /**
     * Loads the real page (actual <body> markup) into a fresh, isolated JSDOM
     * window with stubbed dependencies and returns the fetch URLs observed.
     * A fresh JSDOM per test keeps listeners and state from one test from
     * leaking into the next.
     */
    async function runPage({ filter, accounts, summary } = {}) {
        const htmlSrc = readFileSync(path.resolve(root, 'static/summary.html'), 'utf8');
        const utilsSrc = readFileSync(path.resolve(root, 'static/summary-utils.js'), 'utf8');

        // The real page, with the external utils script inlined so jsdom
        // executes it (external resources are not fetched).
        const pageHtml = htmlSrc.replace(
            '<script src="/static/summary-utils.js"></script>',
            `<script>${utilsSrc}</script>`
        );
        const virtualConsole = new VirtualConsole(); // swallow jsdom noise
        const dom = new JSDOM(pageHtml, {
            url: 'http://localhost/summary',
            runScripts: 'dangerously',
            virtualConsole,
        });
        const win = dom.window;
        const doc = win.document;

        const summaryBody = summary || {
            year: 2026, month: 6, start_date: '2026-06-01', end_date: '2026-06-30',
            is_current_month: false, currency: { code: 'USD', symbol: '$' },
            totals: {
                earned: 0, spent: 0, net: 0, savings_rate: null,
                days_in_month: 30, days_elapsed: 30, daily_average_spent: 0,
                prev_month_earned: null, prev_month_spent: null, prev_month_net: null,
                earned_delta_pct: null, spent_delta_pct: null,
                net_worth: null, net_worth_delta: null,
            },
            budgets: [], budget_totals: {
                count: 0, with_limit: 0, spent: 0, limited: 0,
                limited_spent: 0, over_count: 0,
            },
            categories: [],
            daily: { dates: [], earned: [], spent: [], cumulative_spent: [] },
            trend_12m: {
                labels: [], earned: [], spent: [],
            },
            top_expenses: [], warnings: [],
        };
        const accountsBody = accounts || [
            { id: '1', name: 'Checking', account_type: 'asset', balance: '5000', currency: '$' },
            { id: '3', name: 'Credit Card', account_type: 'liability', balance: '-250', currency: '$' },
        ];

        const fetched = [];
        win.fetch = (url) => {
            fetched.push(String(url));
            return Promise.resolve({
                ok: true,
                json: () => Promise.resolve(
                    String(url).includes('/api/accounts') ? accountsBody : summaryBody
                ),
            });
        };
        win.OxiUI = {
            formatCurrency: (v) => String(v),
            getChartColors: () => ({}),
            spinnerHtml: () => '',
        };
        win.Chart = class {
            constructor() { this.options = {}; }
            destroy() {}
        };
        if (filter) {
            win.localStorage.setItem('oxidize_summary_account_filter', JSON.stringify(filter));
        }

        // The page scripts already ran during parsing; jsdom fires its own
        // (asynchronous) DOMContentLoaded, which triggers init exactly once.
        await new Promise((r) => setTimeout(r, 20));
        return { fetched, doc, win };
    }

    const tick = (ms = 600) => new Promise((r) => setTimeout(r, ms));

    const modeRadio = (doc, value) =>
        doc.querySelector(`input[name="account-filter-mode"][value="${value}"]`);

    const summaryUrls = (fetched) =>
        fetched.filter((u) => u.includes('/api/summary/month'));

    const rowCheckbox = (doc, value) =>
        doc.querySelector(`.acct-checkbox[value="${value}"]`);

    const groupCheckbox = (doc, type) =>
        doc.querySelector(`.acct-group-checkbox[data-type="${type}"]`);

    const setCheckbox = (cb, checked) => {
        cb.checked = checked;
        cb.dispatchEvent(new cb.ownerDocument.defaultView.Event('change', { bubbles: true }));
    };

    it('loads without a filter: no account params in the summary request', async () => {
        const { fetched } = await runPage();
        const urls = summaryUrls(fetched);
        expect(urls).toHaveLength(1);
        expect(urls[0]).not.toContain('accounts');
        expect(urls[0]).not.toContain('exclude_accounts');
    });

    it('renders accounts as grouped checkbox rows with balances', async () => {
        const { doc } = await runPage();
        const list = doc.getElementById('account-filter-accounts');
        const groups = Array.from(list.querySelectorAll('.acct-group'));
        expect(groups.length).toBe(2);
        expect(groups.map((g) => g.querySelector('.acct-group-name').textContent))
            .toEqual(['Assets', 'Liabilities']);
        // Row text carries the balance so accounts are easy to tell apart.
        expect(list.textContent).toContain('Checking');
        expect(list.textContent).toContain('$5000');
        expect(list.textContent).toContain('Credit Card');
        const bal = list.querySelector('.acct-balance.negative');
        expect(bal).toBeTruthy();
        expect(bal.textContent).toBe('$-250');
        expect(doc.getElementById('account-filter-count').textContent).toBe('0 of 2 selected');
        // Group headers expose select-all checkboxes and a collapse control.
        expect(groupCheckbox(doc, 'asset').getAttribute('aria-label')).toBe(
            'Select all 1 Assets accounts');
        expect(list.querySelectorAll('.acct-group-toggle').length).toBe(2);
    });

    it('restores a persisted include filter into the checkbox list', async () => {
        const { fetched, doc } = await runPage({ filter: { mode: 'include', ids: ['1'] } });
        const urls = summaryUrls(fetched);
        expect(urls).toHaveLength(1);
        expect(urls[0]).toContain('accounts[]=1');
        expect(rowCheckbox(doc, '1').checked).toBe(true);
        expect(rowCheckbox(doc, '3').checked).toBe(false);
        expect(modeRadio(doc, 'include').checked).toBe(true);
        expect(doc.getElementById('account-filter-badge').textContent).toBe('1 account included');
        expect(doc.getElementById('summary-meta').textContent).toContain('1 account included');
        // The fully selected group header is checked; the other is not.
        expect(groupCheckbox(doc, 'asset').checked).toBe(true);
        expect(groupCheckbox(doc, 'liability').checked).toBe(false);
    });

    it('sends exclude_accounts[] when an exclude filter is persisted', async () => {
        const { fetched, doc } = await runPage({ filter: { mode: 'exclude', ids: ['3'] } });
        const urls = summaryUrls(fetched);
        expect(urls).toHaveLength(1);
        expect(urls[0]).toContain('exclude_accounts[]=3');
        expect(rowCheckbox(doc, '3').checked).toBe(true);
        expect(modeRadio(doc, 'exclude').checked).toBe(true);
        expect(doc.getElementById('account-filter-badge').textContent).toBe('1 account excluded');
        expect(doc.getElementById('summary-meta').textContent).toContain('1 account excluded');
    });

    it('shows an indeterminate group checkbox for a partially selected group', async () => {
        const { doc } = await runPage({
            filter: { mode: 'include', ids: ['1'] },
            accounts: [
                { id: '1', name: 'Checking', account_type: 'asset', balance: '5000', currency: '$' },
                { id: '2', name: 'Savings', account_type: 'asset', balance: '100', currency: '$' },
                { id: '3', name: 'Credit Card', account_type: 'liability', balance: '-250', currency: '$' },
            ],
        });
        const assetsCb = groupCheckbox(doc, 'asset');
        expect(assetsCb.checked).toBe(false);
        expect(assetsCb.indeterminate).toBe(true);
        // The group count mentions the partial selection.
        expect(doc.querySelector('.acct-group-count[data-idx="0"]').textContent)
            .toBe('(2 \u00b7 1 selected)');
    });

    it('checking a row auto-switches to include and live-applies the filter', async () => {
        const { fetched, doc } = await runPage();
        expect(summaryUrls(fetched)).toHaveLength(1);
        setCheckbox(rowCheckbox(doc, '1'), true);
        // Auto-switch from "All accounts" to "Only selected".
        expect(modeRadio(doc, 'include').checked).toBe(true);
        await tick();
        const urls = summaryUrls(fetched);
        expect(urls).toHaveLength(2);
        expect(urls[1]).toContain('accounts[]=1');
        const stored = JSON.parse(win_stored(doc));
        expect(stored).toEqual({ mode: 'include', ids: ['1'] });
    });

    it('unchecking the last selected row reverts to all accounts', async () => {
        const { fetched, doc } = await runPage({ filter: { mode: 'include', ids: ['1'] } });
        setCheckbox(rowCheckbox(doc, '1'), false);
        expect(modeRadio(doc, 'all').checked).toBe(true);
        await tick();
        const urls = summaryUrls(fetched);
        expect(urls).toHaveLength(2);
        expect(urls[1]).not.toContain('accounts');
        const stored = JSON.parse(win_stored(doc));
        expect(stored).toEqual({ mode: 'all', ids: [] });
    });

    it('a group checkbox selects the whole account type at once', async () => {
        const { fetched, doc } = await runPage({
            accounts: [
                { id: '1', name: 'Checking', account_type: 'asset', balance: '5000', currency: '$' },
                { id: '2', name: 'Savings', account_type: 'asset', balance: '100', currency: '$' },
                { id: '3', name: 'Credit Card', account_type: 'liability', balance: '-250', currency: '$' },
            ],
        });
        setCheckbox(groupCheckbox(doc, 'asset'), true);
        expect(rowCheckbox(doc, '1').checked).toBe(true);
        expect(rowCheckbox(doc, '2').checked).toBe(true);
        expect(rowCheckbox(doc, '3').checked).toBe(false);
        await tick();
        const urls = summaryUrls(fetched);
        expect(urls).toHaveLength(2);
        expect(urls[1]).toContain('accounts[]=1');
        expect(urls[1]).toContain('accounts[]=2');
        expect(urls[1]).not.toContain('accounts[]=3');
    });

    it('search narrows the list to matching accounts', async () => {
        const { doc } = await runPage({
            accounts: [
                { id: '1', name: 'Checking', account_type: 'asset', balance: '5000', currency: '$' },
                { id: '2', name: 'Savings', account_type: 'asset', balance: '100', currency: '$' },
                { id: '3', name: 'Credit Card', account_type: 'liability', balance: '-250', currency: '$' },
            ],
        });
        const search = doc.getElementById('account-filter-search');
        search.value = 'savi';
        search.dispatchEvent(new doc.defaultView.Event('input', { bubbles: true }));
        const rows = Array.from(doc.querySelectorAll('.acct-row'));
        expect(rows.length).toBe(1);
        expect(rows[0].textContent).toContain('Savings');
        // The group count reflects the visible accounts only.
        expect(doc.querySelector('.acct-group-count').textContent).toBe('(1)');
    });

    it('shows a "no match" empty state for a search that matches nothing', async () => {
        const { doc } = await runPage();
        const search = doc.getElementById('account-filter-search');
        search.value = 'zzz';
        search.dispatchEvent(new doc.defaultView.Event('input', { bubbles: true }));
        expect(doc.getElementById('account-filter-accounts').textContent)
            .toContain('No accounts match');
    });

    it('Select all shown / Clear shown operate on the visible rows', async () => {
        const { fetched, doc } = await runPage({
            accounts: [
                { id: '1', name: 'Checking', account_type: 'asset', balance: '5000', currency: '$' },
                { id: '2', name: 'Savings', account_type: 'asset', balance: '100', currency: '$' },
                { id: '3', name: 'Credit Card', account_type: 'liability', balance: '-250', currency: '$' },
            ],
        });
        // Search to two asset accounts: only matching rows are "shown".
        const search = doc.getElementById('account-filter-search');
        search.value = 's';
        search.dispatchEvent(new doc.defaultView.Event('input', { bubbles: true }));
        doc.getElementById('account-filter-select-all').click();
        // Only the row matching the search is "shown", so only it is selected.
        const rows = Array.from(doc.querySelectorAll('.acct-row'));
        expect(rows).toHaveLength(1);
        expect(rows[0].textContent).toContain('Savings');
        expect(rowCheckbox(doc, '2').checked).toBe(true);
        expect(rowCheckbox(doc, '1')).toBe(null);
        expect(rowCheckbox(doc, '3')).toBe(null);
        expect(modeRadio(doc, 'include').checked).toBe(true);
        doc.getElementById('account-filter-clear').click();
        expect(rowCheckbox(doc, '2').checked).toBe(false);
        expect(modeRadio(doc, 'all').checked).toBe(true);
        await tick();
        const urls = summaryUrls(fetched);
        // Only the debounced reload for the final (empty) state arrives.
        expect(urls[urls.length - 1]).not.toContain('accounts');
    });

    it('collapsing a group hides its rows', async () => {
        const { doc } = await runPage();
        // The list re-renders on toggle, so re-query after each click.
        doc.querySelector('.acct-group-toggle[data-type="asset"]').click();
        let group = doc.querySelector('.acct-group[data-type="asset"]');
        expect(group.classList.contains('collapsed')).toBe(true);
        expect(group.querySelector('.acct-group-toggle').getAttribute('aria-expanded')).toBe('false');
        group.querySelector('.acct-group-toggle').click();
        group = doc.querySelector('.acct-group[data-type="asset"]');
        expect(group.classList.contains('collapsed')).toBe(false);
        expect(group.querySelector('.acct-group-toggle').getAttribute('aria-expanded')).toBe('true');
    });

    it('reset clears the filter and reloads with all accounts', async () => {
        const { fetched, doc } = await runPage({ filter: { mode: 'exclude', ids: ['3'] } });
        expect(summaryUrls(fetched)[0]).toContain('exclude_accounts[]=3');
        doc.getElementById('account-filter-reset').click();
        expect(modeRadio(doc, 'all').checked).toBe(true);
        expect(rowCheckbox(doc, '3').checked).toBe(false);
        await tick();
        const urls = summaryUrls(fetched);
        expect(urls).toHaveLength(2);
        expect(urls[1]).not.toContain('exclude_accounts');
        const stored = JSON.parse(win_stored(doc));
        expect(stored).toEqual({ mode: 'all', ids: [] });
    });

    it('prunes stale ids from a persisted filter', async () => {
        const { fetched } = await runPage({ filter: { mode: 'include', ids: ['1', '999'] } });
        const summaryUrl = summaryUrls(fetched)[0];
        expect(summaryUrl).toContain('accounts[]=1');
        expect(summaryUrl).not.toContain('accounts[]=999');
    });

    function win_stored(doc) {
        return doc.defaultView.localStorage.getItem('oxidize_summary_account_filter');
    }
});
