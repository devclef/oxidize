// @vitest-environment jsdom
/**
 * Account include/exclude filter on the Monthly Summary page (/summary):
 * the page must let the user choose which accounts the summary counts via a
 * grouped, searchable checkbox list, persist that choice, and send it to the
 * API as accounts[] (include) or exclude_accounts[] (exclude). Selection
 * changes apply automatically (debounced) — there is no Apply button.
 */
import { describe, it, expect } from 'vitest';
import { JSDOM, VirtualConsole } from 'jsdom';
import { readFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const html = readFileSync(path.resolve(root, 'static/summary.html'), 'utf8');
const css = readFileSync(path.resolve(root, 'static/style.css'), 'utf8');
const utils = readFileSync(path.resolve(root, 'static/summary-utils.js'), 'utf8');

describe('summary page account filter markup', () => {
    it('has an Accounts toggle button in the page header', () => {
        expect(html).toContain('id="account-filter-toggle"');
        expect(html).toContain('id="account-filter-badge"');
        expect(html).toContain('aria-controls="account-filter-panel"');
    });

    it('has a filter panel with mode choices, search, list and actions', () => {
        expect(html).toContain('id="account-filter-panel"');
        expect(html).toContain('id="account-filter-mode"');
        expect(html).toContain('name="account-filter-mode"');
        expect(html).toContain('id="account-filter-search"');
        expect(html).toContain('id="account-filter-accounts"');
        expect(html).toContain('id="account-filter-select-all"');
        expect(html).toContain('id="account-filter-clear"');
        expect(html).toContain('id="account-filter-reset"');
        expect(html).toContain('id="account-filter-count"');
    });

    it('replaced the clunky multi-select with a checkbox list (no Apply button)', () => {
        expect(html).not.toContain('id="account-filter-apply"');
        expect(html).not.toContain('<select multiple');
        expect(html).not.toContain('class="exclusion-select"');
        // The checkbox list is generated by the page script.
        expect(html).toContain('acct-checkbox');
        expect(html).toContain('acct-group-checkbox');
        expect(html).toContain('acct-group-toggle');
        expect(html).toContain('type="search"');
    });

    it('offers all-accounts, include-only and exclude modes as a radiogroup', () => {
        expect(html).toContain('role="radiogroup"');
        expect(html).toMatch(/<input type="radio" name="account-filter-mode" value="all"/);
        expect(html).toMatch(/<input type="radio" name="account-filter-mode" value="include"/);
        expect(html).toMatch(/<input type="radio" name="account-filter-mode" value="exclude"/);
    });
});

describe('summary page account filter wiring', () => {
    it('sends the account filter with the API request', () => {
        expect(html).toContain('MonthSummary.buildAccountFilterParams(');
        expect(html).toMatch(/buildAccountFilterParams\(accountFilter\.mode,\s*accountFilter\.ids\)/);
    });

    it('persists and restores the filter via localStorage', () => {
        expect(html).toContain('MonthSummary.ACCOUNT_FILTER_KEY');
        expect(html).toMatch(/localStorage\.getItem\(MonthSummary\.ACCOUNT_FILTER_KEY\)/);
        expect(html).toMatch(/localStorage\.setItem\(MonthSummary\.ACCOUNT_FILTER_KEY/);
    });

    it('applies selection changes automatically (debounced) instead of an Apply button', () => {
        expect(html).toContain('function scheduleApply()');
        expect(html).toMatch(/setTimeout\([\s\S]*?loadSummary\(\)[\s\S]*?applyDelayMs/);
        // Every mutating path goes through setFilter, which schedules the reload.
        expect(html).toContain('function setFilter(mode, ids)');
        expect(html).toMatch(/function setFilter[\s\S]*?scheduleApply\(\)/);
    });

    it('resets the filter to all accounts on Reset', () => {
        const resetIdx = html.lastIndexOf("getElementById('account-filter-reset')");
        expect(resetIdx).toBeGreaterThan(-1);
        const handler = html.slice(resetIdx, resetIdx + 200);
        expect(handler).toContain('onReset');
        const onResetIdx = html.indexOf('function onReset()');
        expect(onResetIdx).toBeGreaterThan(-1);
        const onResetSrc = html.slice(onResetIdx, onResetIdx + 200);
        expect(onResetSrc).toContain("'all'");
        expect(onResetSrc).toContain('renderAccountFilter()');
    });

    it('prunes stale ids from the persisted filter after loading accounts', () => {
        expect(html).toMatch(/loadAccounts\(\)\s*\.then\(/);
        expect(html).toContain('pruneStaleIds()');
        expect(html).toContain("/api/accounts");
    });

    it('shows the active filter in the summary meta line', () => {
        expect(html).toContain('MonthSummary.describeAccountFilter(');
    });

    it('groups accounts by type for the list and derives the mode from the selection', () => {
        expect(html).toContain('MonthSummary.groupAccounts(');
        expect(html).toContain('MonthSummary.resolveFilterMode(');
    });
});

